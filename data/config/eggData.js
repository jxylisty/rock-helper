export function predictEgg(height, weight) {
	const predictions = []

	eggData.forEach(egg => {
		let score = 0
		let heightMatch = false
		let weightMatch = false

		if (height >= egg.minHeight && height <= egg.maxHeight) {
			heightMatch = true
			const centerH = (egg.minHeight + egg.maxHeight) / 2
			const rangeH = egg.maxHeight - egg.minHeight || 0.01
			const diffH = Math.abs(height - centerH) / rangeH
			score += (1 - Math.min(diffH, 1)) * 50
		}

		if (weight >= egg.minWeight && weight <= egg.maxWeight) {
			weightMatch = true
			const centerW = (egg.minWeight + egg.maxWeight) / 2
			const rangeW = egg.maxWeight - egg.minWeight || 0.01
			const diffW = Math.abs(weight - centerW) / rangeW
			score += (1 - Math.min(diffW, 1)) * 50
		}

		if (heightMatch || weightMatch) {
			predictions.push({
				...egg,
				score: Math.round(score),
				heightMatch,
				weightMatch,
				matchType: heightMatch && weightMatch ? 'full' : (heightMatch ? 'height' : 'weight')
			})
		}
	})

	return predictions.sort((a, b) => b.score - a.score).slice(0, 10)
}

// 大块头判定口径：身高与体重须同时达到该精灵蛋范围的 98% 分位（双维度缺一不可）。
// 校准依据：罗隐蛋官方区间 13.475~19.68kg，社区实测准入 >19.556kg = min + 0.98×(max-min)，完全吻合。
const BULK_RATIO = 0.98

export function judgeBulkEgg(egg, height, weight) {
	const rangeH = (egg.maxHeight - egg.minHeight) || 0
	const rangeW = (egg.maxWeight - egg.minWeight) || 0
	const heightThreshold = egg.minHeight + rangeH * BULK_RATIO
	const weightThreshold = egg.minWeight + rangeW * BULK_RATIO
	const heightOk = height >= heightThreshold
	const weightOk = weight >= weightThreshold
	return {
		isBulk: heightOk && weightOk,
		heightOk,
		weightOk,
		heightThreshold,
		weightThreshold,
		heightRatio: rangeH ? (height - egg.minHeight) / rangeH : 0,
		weightRatio: rangeW ? (weight - egg.minWeight) / rangeW : 0
	}
}

